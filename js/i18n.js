/* ---------- Latinica -> ćirilica ---------- */
(function () {
  const pairs = [
    ["DŽ", "Џ"], ["Dž", "Џ"], ["dž", "џ"],
    ["LJ", "Љ"], ["Lj", "Љ"], ["lj", "љ"],
    ["NJ", "Њ"], ["Nj", "Њ"], ["nj", "њ"]
  ];
  const single = {
    A: "А", B: "Б", V: "В", G: "Г", D: "Д", Đ: "Ђ", E: "Е", Ž: "Ж", Z: "З", I: "И",
    J: "Ј", K: "К", L: "Л", M: "М", N: "Н", O: "О", P: "П", R: "Р", S: "С", T: "Т",
    Ć: "Ћ", U: "У", F: "Ф", H: "Х", C: "Ц", Č: "Ч", Š: "Ш",
    a: "а", b: "б", v: "в", g: "г", d: "д", đ: "ђ", e: "е", ž: "ж", z: "з", i: "и",
    j: "ј", k: "к", l: "л", m: "м", n: "н", o: "о", p: "п", r: "р", s: "с", t: "т",
    ć: "ћ", u: "у", f: "ф", h: "х", c: "ц", č: "ч", š: "ш"
  };
  // Reči koje ostaju latinicom (naziv firme, adrese, brojevi telefona...)
  const keep = /(TermoVolt|[\w.+-]+@[\w.-]+|https?:\/\/\S+|\+?\d[\d\s/-]{5,})/g;

  function convert(part) {
    let out = "";
    for (let i = 0; i < part.length; i++) {
      const two = part.substr(i, 2);
      const p = pairs.find(x => x[0] === two);
      if (p) { out += p[1]; i++; continue; }
      const ch = part[i];
      out += single[ch] !== undefined ? single[ch] : ch;
    }
    return out;
  }

  window.toCyrillic = function (text) {
    if (!text) return text;
    return text.split(keep).map((part, idx) => (idx % 2 === 1 ? part : convert(part))).join("");
  };
})();

